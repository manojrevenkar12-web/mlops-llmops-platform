"""`paved init`: a new workload in one command. The files it writes are the whole onboarding: a contract, a code
stub that implements the platform interface, a test, and the CI job that runs the release path on merge."""

from __future__ import annotations

from pathlib import Path

from paved.contract import Workload

MODEL_CODE = '''"""{name}: training code. Implement train() returning an object with features(data, online),
predict(frame), train_to and complexity. See docs/handbook.md#models."""


def train(data, spec):
    raise NotImplementedError("train your model here")
'''

AGENT_CODE = '''"""{name}: agent code. Build a graph against paved.agentkit (LLM and Tools ports) and expose
handle(inquiry_id, text) -> dict. See docs/handbook.md#agents."""

from paved.agentkit import LLM, Tools


class Agent:
    def __init__(self, version, llm: LLM, tools: Tools):
        self.version, self.llm, self.tools = version, llm, tools

    def handle(self, inquiry_id: str, text: str) -> dict:
        raise NotImplementedError("wire your graph here")
'''

CONTRACT_TEST = """from paved.contract import load


def test_contract():
    load("{path}")
"""

CI = """# Generated by `paved init`. Runs the release path for this workload when its code or contract changes.
name: release-{name}
on:
  push:
    branches: [main]
    paths: ["workloads/{name}/**"]
jobs:
  release:
    runs-on: ubuntu-latest
    permissions: {{ id-token: write, contents: read }}
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with: {{ python-version: "3.12" }}
      - run: pip install -e .
      - run: paved validate workloads/{name}/workload.yaml
      - run: python -m pytest -q workloads/{name}
      # Hand the release to the control plane; it runs offline, shadow and canary and reports back.
      - run: >
          curl -fsS -X POST "${{{{ vars.PAVED_API }}}}/releases"
          -H "Authorization: Bearer ${{{{ secrets.PAVED_TOKEN }}}}"
          -d '{{"workload": "{name}", "commit": "${{{{ github.sha }}}}"}}'
"""


def init(root: Path, name: str, kind: str, team: str, owner: str) -> list[Path]:
    module = name.replace("-", "_")
    contract = {
        "name": name,
        "kind": kind,
        "team": team,
        "owner": owner,
        "entrypoint": f"workloads.{module}.code:{'train' if kind == 'model' else 'Agent'}",
        "budget_usd_month": 500,
    }
    if kind == "model":
        contract["serving"] = {"target": "sagemaker-realtime", "instance_type": "ml.m5.large", "instance_count": 1}
        contract["evaluation"] = {"label": "label", "metric": "logloss", "slices": []}
    else:
        contract["serving"] = {"target": "bedrock-agentcore", "latency_class": "interactive"}
        contract["model_id"] = "anthropic.claude-haiku-4-5"
    Workload.model_validate(contract)  # the scaffold never writes a contract that would not validate

    import yaml

    d = root / "workloads" / name
    d.mkdir(parents=True, exist_ok=False)
    files = {
        d / "workload.yaml": yaml.safe_dump(contract, sort_keys=False),
        d / "code.py": (MODEL_CODE if kind == "model" else AGENT_CODE).format(name=name),
        d / "test_contract.py": CONTRACT_TEST.format(path=d / "workload.yaml"),
        root / ".github" / "workflows" / f"release-{name}.yml": CI.format(name=name),
    }
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return list(files)
