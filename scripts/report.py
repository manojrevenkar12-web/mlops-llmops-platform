"""RESULTS.md and web/public/data/dashboard.json, generated from reports/*.json. CI regenerates both and fails on a
difference, so neither is ever edited by hand.

    python scripts/report.py
"""

from __future__ import annotations

import json
from pathlib import Path

from paved.settings import ROOT, settings

POLICY = {
    "platform": "This release path",
    "fixed_canary": "10% canary, one z-test",
    "offline_only": "Offline metric, then 100%",
}


def stopped_at(policy: str, row: dict) -> str:
    d = row[policy]["decision"]
    if d == "promoted":
        return "shipped"
    if policy == "platform":
        return row["platform"]["stage"]
    return "offline" if policy == "offline_only" else "canary_0"


def release(row: dict) -> dict:
    p = row["platform"]
    return {
        "id": row["id"],
        "workload": row["workload"],
        "kind": "model" if row["workload"] == "pricing-conversion" else "agent",
        "scenario": row["kind"],
        "note": row["note"],
        "truthGood": row["truth_good"],
        "truthWhy": row["truth_why"],
        "trueEffect": row["true_effect"],
        "decisions": {k: {"decision": row[k]["decision"], "stoppedAt": stopped_at(k, row)} for k in POLICY},
        "reason": p["reason"],
        "exposure": p["exposure"],
        "hours": p["hours"],
        "steps": [
            {
                k: s[k]
                for k in ("step", "share", "effect", "lower", "upper", "margin", "decision", "reason", "n_candidate")
            }
            for s in p["steps"]
        ],
        "gates": {g: {"passed": v["passed"], "checks": v["checks"]} for g, v in row.get("gates", {}).items()},
    }


def load(name: str) -> dict | None:
    p = ROOT / "reports" / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def table(summary: dict) -> list[str]:
    out = [
        "| Way of releasing | Bad releases shipped | Good releases shipped "
        "| Requests served by bad releases before a stop | Median hours to a decision |",
        "|---|---|---|---|---|",
    ]
    for k, name in POLICY.items():
        s = summary[k]
        out.append(
            f"| {name} | {s['bad_shipped']} of {s['bad']} | {s['good_shipped']} of {s['good']} | "
            f"{s['bad_exposure_requests']:,} | {s['median_hours_to_decision']:.0f} |"
        )
    return out


def main() -> None:
    ev = settings()["evaluation"]
    sets = []
    md = ["# Results", "", "Generated by `scripts/report.py` from `reports/*.json`. Do not edit by hand.", ""]
    for name, title in (("heldout", "Held-out releases"), ("dev", "Development releases")):
        rep = load(name)
        if rep is None:
            continue
        sets.append(
            {
                "name": name,
                "title": title,
                "seeds": rep["seeds"],
                "unseenKinds": ev["heldout_only_kinds"] if name == "heldout" else [],
                "summary": rep["summary"],
                "releases": [release(r) for r in rep["rows"]],
            }
        )
        md += [
            f"## {title}",
            "",
            f"Seeds {rep['seeds']}; {len(rep['rows'])} releases ({rep['summary']['platform']['bad']} bad, "
            f"{rep['summary']['platform']['good']} good by the world's truth); {rep['minutes']} minutes.",
            "",
        ]
        md += table(rep["summary"]) + [""]
        for wl, s in rep["summary_by_workload"].items():
            md += [f"### {wl}", ""] + table(s) + [""]
        md += [
            "| Release | Truth | This path | Where | Why | 10% canary | Offline only |",
            "|---|---|---|---|---|---|---|",
        ]
        for r in rep["rows"]:
            truth = "good" if r["truth_good"] else "bad: " + "; ".join(r["truth_why"])
            md.append(
                f"| {r['id']} | {truth} | {r['platform']['decision']} | {r['platform']['stage']} | "
                f"{r['platform']['reason'].replace('|', '/')[:140]} | {r['fixed_canary']['decision']} "
                f"| {r['offline_only']['decision']} |"
            )
        md.append("")
    cost = load("cost")
    if cost:
        md += [
            "## Cost",
            "",
            cost["note"],
            "",
            f"Spend ${cost['total_spend_usd_month']:,.0f} a month; "
            f"identified saving ${cost['identified_saving_usd_month']:,.0f} a month.",
            "",
            "| Team | Workload | Action | Saving a month |",
            "|---|---|---|---|",
        ]
        md += [
            f"| {r['team']} | {r['workload']} | {r['action']} | ${r['saving_usd_month']:,.0f} |"
            for r in cost["recommendations"]
        ]
        md.append("")
    (ROOT / "RESULTS.md").write_text("\n".join(md))
    out = ROOT / "web" / "public" / "data" / "dashboard.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        json.dumps({"generated": "scripts/report.py", "sets": sets, "cost": cost}, indent=1, default=float) + "\n"
    )
    print(f"wrote RESULTS.md and {Path(out).relative_to(ROOT)}")


if __name__ == "__main__":
    main()
